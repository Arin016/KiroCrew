"""Persistence for reports, analyses and human decisions.

Layout under the app's data dir (``~/.kiro/crew/workspace/pr-postmortem``)::

    reports/<fix_pr>.json              attribution report (mechanical)
    analysis/analysis-<fix_pr>.json    postmortem verdict (model, schema-checked)
    bundles/bundle-<fix_pr>.json       raw evidence the analysis was based on
    decisions.json                     human accept / reject -- the only file the UI writes
    state.json                         scan bookkeeping

Decisions live in their own file on purpose: the report files are regenerated by
every scan, and a human's accept must never be destroyed by a re-run.
"""

from __future__ import annotations

import json
import os
import tempfile
import threading
import time
from contextlib import contextmanager
from typing import Iterator

from kiro_crew import platform_compat
from kiro_crew.apps.builtins.pr_postmortem.engine import analysis

# Matches app.json's `name`. ``is_app_enabled`` keys on it, so the two must agree
# or the enabled-gate would refuse every request for an app that is switched on.
APP_NAME = "pr-postmortem"

# Guards read-modify-write of decisions.json and state.json.
#
# TWO writers exist, in two PROCESSES: the gateway (whose handlers interleave
# around awaits) and the `engine.cli` commands a cron or a human runs. A
# `threading.Lock` alone is therefore not enough -- it serialized the coroutines
# and did nothing about the CLI, so a forced re-analysis overlapping a dashboard
# decision could read, modify and write from two stale snapshots and drop one of
# them. Every critical section now takes the thread lock AND an advisory
# `file_lock` on a dedicated lock file beside the target.
#
# The thread lock stays as the outer guard: `file_lock` is single-shot on the
# asyncio thread on Windows, so letting two coroutines race for it would make one
# of them fail closed rather than wait. Found by review on PR #2354.
_LOCK = threading.Lock()


@contextmanager
def _exclusive(target_path: str) -> Iterator[None]:
    """Serialize a read-modify-write of ``target_path`` across threads AND processes.

    The lock lives in a SEPARATE ``<target>.lock`` file rather than on the target
    itself, because the target is replaced by an atomic rename (which would drop a
    lock held on the old inode) and because `msvcrt.locking` needs to seek to byte
    0 of a file it owns. `file_lock` fails closed, so a caller never proceeds
    unserialized.

    Not reentrant: a critical section must not call another one (both the thread
    lock and a second `flock` on a different fd would deadlock).
    """
    lock_path = f"{target_path}.lock"
    os.makedirs(os.path.dirname(lock_path) or ".", exist_ok=True)
    fd = os.open(lock_path, os.O_RDWR | os.O_CREAT, 0o600)
    try:
        with _LOCK, platform_compat.file_lock(fd, exclusive=True, required=True):
            yield
    finally:
        os.close(fd)


DECISIONS = ("accept", "reject", "defer")
LINK_DECISIONS = ("confirmed", "not_a_culprit")
# Lifecycle of a backlog cluster being turned into a real change.
APPLICATION_STATUSES = ("requested", "applied", "failed")


def data_dir() -> str:
    """Resolve the app's data directory.

    ``PRPM_DATA_DIR`` wins (tests, pods), then ``KIROCREW_HOME``, then the default.
    """
    override = os.environ.get("PRPM_DATA_DIR")
    if override:
        return override
    home = os.environ.get("KIROCREW_HOME") or os.path.join(
        os.path.expanduser("~"), ".kiro", "crew"
    )
    return os.path.join(home, "workspace", "pr-postmortem")


def _sub(name: str) -> str:
    path = os.path.join(data_dir(), name)
    os.makedirs(path, exist_ok=True)
    return path


def reports_dir() -> str:
    return _sub("reports")


def analysis_dir() -> str:
    return _sub("analysis")


def bundles_dir() -> str:
    return _sub("bundles")


def decisions_path() -> str:
    return os.path.join(data_dir(), "decisions.json")


def state_path() -> str:
    return os.path.join(data_dir(), "state.json")


def _read_json(path: str) -> dict | None:
    try:
        with open(path, encoding="utf-8") as fh:
            obj = json.load(fh)
        return obj if isinstance(obj, dict) else None
    except (FileNotFoundError, json.JSONDecodeError):
        return None


def _write_json_atomic(path: str, obj: object) -> None:
    """Write via temp file + replace so a crash cannot truncate a decision file."""
    os.makedirs(os.path.dirname(path), exist_ok=True)
    fd, tmp = tempfile.mkstemp(dir=os.path.dirname(path), suffix=".tmp")
    try:
        with os.fdopen(fd, "w", encoding="utf-8") as fh:
            json.dump(obj, fh, indent=2)
        os.replace(tmp, path)
    except BaseException:
        try:
            os.unlink(tmp)
        except OSError:
            pass
        raise


# Public aliases. Other engine modules serialize and write JSON through THESE
# rather than hand-rolling a second lock + atomic-rename pair -- bundle.py's own
# copy was neither locked nor atomic, which is the defect that prompted this.
exclusive = _exclusive
write_json_atomic = _write_json_atomic

# ── proposal identity ────────────────────────────────────────────────────────


def proposal_id(fix_pr: int, index: int) -> str:
    return f"{fix_pr}:{index}"


# A pull-request number and a proposal index are both small by construction. The
# bound exists because `int()` RAISES above 4300 digits on Python 3.11+, so an
# unbounded digit string reaching the conversion below crashed the caller instead
# of being rejected. Bounded here, at the shared parser, rather than at one
# handler -- every caller reaches this function. Found by review on PR #2354.
MAX_ID_DIGITS = 9


def parse_proposal_id(pid: str) -> tuple[int, int] | None:
    fix, sep, idx = pid.partition(":")
    if not sep or not fix.isdigit() or not idx.isdigit():
        return None
    if len(fix) > MAX_ID_DIGITS or len(idx) > MAX_ID_DIGITS:
        return None
    return int(fix), int(idx)


# ── decisions ────────────────────────────────────────────────────────────────


def retire_analysis(fix_pr: int, *, culprit_changed: bool = False) -> bool:
    """Move an invalidated analysis out of the active path. Returns True if moved.

    Called when re-attribution names a different culprit: every judgement in the
    analysis reasoned about the old pull request, so leaving it in place would keep
    its proposals acceptable -- and appliable -- against a PR they were never about.

    Renamed rather than deleted. The analysis cost a model call, and a human may
    want to compare what the tool believed before the culprit moved; the retired
    copy sits beside it as ``analysis-<pr>.retired-<n>.json`` and nothing reads it.
    """
    live = os.path.join(analysis_dir(), f"analysis-{fix_pr}.json")
    if not os.path.exists(live):
        return False
    # Retiring the analysis MUST also drop the pair's decisions. Proposal ids are
    # positional (`<fix_pr>:<index>`), so a human's "accept" on index 2 would
    # otherwise be inherited by whatever new proposal lands at index 2 in the
    # replacement analysis -- applying a decision to something nobody read.
    #
    # The clearing sits at the SINGLE exit below rather than next to each disposal,
    # because this function has two ways to succeed (rename to a retired copy, or
    # delete once 99 copies exist) and an earlier fix guarded only the first one.
    # A guard on one exit of a two-exit chokepoint is not a guard.
    # Found by review on PR #2354.
    disposed = False
    for n in range(1, 100):
        dest = os.path.join(analysis_dir(), f"analysis-{fix_pr}.retired-{n}.json")
        if not os.path.exists(dest):
            os.replace(live, dest)
            disposed = True
            break
    if not disposed:
        # 99 retirements for one pair means something is looping; drop the file
        # rather than growing the directory without bound.
        os.remove(live)

    clear_decisions_for(fix_pr)
    if culprit_changed:
        # The link ruling is ATTRIBUTION-specific: a human confirming "yes, this
        # is the culprit" said that about the OLD pull request. Keeping it across a
        # culprit change transfers a human judgement onto a PR they never saw.
        # A forced re-analysis of the SAME culprit keeps the ruling, which is still
        # valid. Found by review on PR #2354.
        clear_link_decision_for(fix_pr)
    return True


def clear_decisions_for(fix_pr: int) -> int:
    """Drop every decision recorded for one fix PR. Returns how many were removed.

    Used before a forced re-analysis: proposal ids are positional
    (``<fix_pr>:<index>``), so keeping decisions across a rewritten proposal list
    would move a human's accept onto a different proposal.
    """
    with _exclusive(decisions_path()):
        dec = load_decisions()
        props = dec.get("proposals") or {}
        prefix = f"{fix_pr}:"
        doomed = [key for key in props if key.startswith(prefix)]
        for key in doomed:
            props.pop(key, None)
        if doomed:
            dec["proposals"] = props
            _write_json_atomic(decisions_path(), dec)
        return len(doomed)


def clear_link_decision_for(fix_pr: int) -> bool:
    """Drop the human ruling on one pair's attribution. True if one was removed.

    Separate from `clear_decisions_for` because the two have different lifetimes:
    proposal decisions are invalidated by ANY re-analysis (their ids are
    positional), while the link ruling only stops being true when the culprit
    itself changes.
    """
    with _exclusive(decisions_path()):
        dec = load_decisions()
        links = dec.get("links") or {}
        if str(fix_pr) not in links:
            return False
        links.pop(str(fix_pr), None)
        dec["links"] = links
        _write_json_atomic(decisions_path(), dec)
        return True


def load_decisions() -> dict:
    obj = _read_json(decisions_path()) or {}
    obj.setdefault("proposals", {})
    obj.setdefault("links", {})
    obj.setdefault("applications", {})
    return obj


def set_application(
    cluster_id: str, status: str, target: str = "", note: str = "", url: str = ""
) -> dict:
    """Record that an accepted backlog cluster is being (or has been) applied.

    Lives with the decisions rather than the reports for the same reason: a scan
    rewrites reports, and losing the record would re-offer work already done.
    """
    if status not in APPLICATION_STATUSES:
        raise ValueError(f"status must be one of {APPLICATION_STATUSES}")
    if not cluster_id or not str(cluster_id).isalnum():
        raise ValueError("cluster id must be alphanumeric")
    with _exclusive(decisions_path()):
        data = load_decisions()
        prev = data["applications"].get(cluster_id) or {}

        # A finished record is not overwritten by a fresh request. The page posts
        # `requested` as soon as it hands the plan to an agent, so clicking Apply
        # again on a cluster that had already completed replaced `applied` -- URL,
        # timestamp and all -- with a pending state, losing the only evidence that
        # the work had ever landed. `applied` is terminal; anything else may still
        # move. Same rule as save_attribution's: a re-run must not lose a result.
        # Found by review on PR #2354.
        if prev.get("status") == "applied" and status == "requested":
            return prev

        data["applications"][cluster_id] = {
            "status": status,
            "target": target or prev.get("target", ""),
            "note": note[:2000] or prev.get("note", ""),
            "url": url or prev.get("url", ""),
            "at": time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime()),
        }
        _write_json_atomic(decisions_path(), data)
        return data["applications"][cluster_id]


def load_applications() -> dict:
    return load_decisions()["applications"]


def set_proposal_decision(
    pid: str, decision: str, note: str = "", *, require_proposal: bool = True
) -> dict:
    """Record a human decision on one proposal.

    ``require_proposal`` verifies the proposal still exists INSIDE the lock that
    guards the write. Checking first and writing afterwards was a race: a scan
    could retire the analysis in between, and the decision then landed against a
    proposal list that no longer existed. Raises ``LookupError`` whose message is
    the caller's error code. Defaults to ON -- the safe direction -- so only a
    caller that knowingly has no report on disk opts out.
    Found by review on PR #2354.
    """
    if decision not in DECISIONS:
        raise ValueError(f"decision must be one of {DECISIONS}")
    parsed = parse_proposal_id(pid)
    if parsed is None:
        raise ValueError("malformed proposal id")
    with _exclusive(decisions_path()):
        if require_proposal:
            report = load_report(parsed[0], include_evidence=False)
            if report is None:
                raise LookupError("report_not_found")
            if not any(p.get("id") == pid for p in report.get("proposals") or []):
                raise LookupError("proposal_not_found")
        data = load_decisions()
        data["proposals"][pid] = {
            "decision": decision,
            "note": note[:2000],
            "at": time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime()),
        }
        _write_json_atomic(decisions_path(), data)
        return data["proposals"][pid]


def set_link_decision(fix_pr: int, decision: str, note: str = "") -> dict:
    """Record a human ruling on whether the attribution itself is right.

    ``not_a_culprit`` is the correction path for a bad blame link -- the single
    most important human input, since a wrong culprit yields a wrong rule.
    """
    if decision not in LINK_DECISIONS:
        raise ValueError(f"decision must be one of {LINK_DECISIONS}")
    with _exclusive(decisions_path()):
        data = load_decisions()
        data["links"][str(fix_pr)] = {
            "decision": decision,
            "note": note[:2000],
            "at": time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime()),
        }
        _write_json_atomic(decisions_path(), data)
        return data["links"][str(fix_pr)]


# ── reports ──────────────────────────────────────────────────────────────────


def save_attribution(report: dict) -> str:
    """Write one attribution report. Refuses to DOWNGRADE an existing one.

    Every writer funnels through here -- the nightly scan (`batch` ->
    `import-reports`) and the re-attribute route both -- so the "a re-run must
    never lose evidence" rule belongs here rather than in one caller. A run that
    names no candidate while the stored report names one is a failure of this
    environment (the clone moved on, the commit is unreachable, `gh` lost its
    auth), not a finding: saving it would delete a good report and its evidence.

    Returns the path written, or the existing path unchanged when the write was
    refused -- callers that need to tell the difference compare `culprit_pr`.
    Found by review on PR #2354.
    """
    fix_pr = int(report.get("fix_pr", 0))
    path = os.path.join(reports_dir(), f"{fix_pr}.json")

    if not (report.get("candidates") or []):
        existing = _read_json(path)
        if existing and (existing.get("candidates") or []):
            return path

    _write_json_atomic(path, report)
    return path


def import_jsonl(jsonl_path: str) -> int:
    """Split a batch JSONL into per-PR report files. Returns the count written."""
    n = 0
    with open(jsonl_path, encoding="utf-8") as fh:
        for line in fh:
            if not line.strip():
                continue
            try:
                rec = json.loads(line)
            except json.JSONDecodeError:
                continue
            if isinstance(rec, dict) and rec.get("fix_pr"):
                save_attribution(rec)
                n += 1
    return n


def load_report(fix_pr: int, include_evidence: bool = True) -> dict | None:
    """Merge attribution + analysis + decisions into one report view.

    Diffs are deliberately NOT included -- they live in the bundle and would make
    a list response enormous. The UI fetches a bundle only when a human drills in.
    """
    att = _read_json(os.path.join(reports_dir(), f"{fix_pr}.json"))
    if att is None:
        return None
    # Validate the analysis HERE, not only in the CLI checker. This is the load
    # path the HTTP routes and the backlog use, so an analysis that never passed
    # `check-analysis` (hand-edited, or written by an older schema) would otherwise
    # flow into the apply prompt with a root-cause class nothing had vetted. A
    # failing analysis is DISCARDED: the attribution still renders, the pair simply
    # reads as un-analysed, which is the honest state. Found by review on PR #2354.
    ana, ana_errors = analysis.load_and_validate(
        os.path.join(analysis_dir(), f"analysis-{fix_pr}.json")
    )
    if ana_errors or not isinstance(ana, dict):
        ana = {}
    dec = load_decisions()

    cands = att.get("candidates") or []
    top = cands[0] if cands else {}

    # The analysis must agree with the attribution about WHO the culprit is.
    #
    # Matching on the filename alone was not enough: `post_reattribute` retires a
    # stale analysis, but a scan-driven re-attribution moves the culprit without
    # going through that route, and the old analysis -- still named
    # `analysis-<fix_pr>.json` -- would attach to the new attribution and describe
    # a pull request that is no longer the culprit. Every judgement in it, and
    # every proposal drawn from it, would be about the wrong PR.
    #
    # Equality is the ONLY passing case -- including `None == None`, which means
    # both sides agree there is no culprit PR (a culprit commit that predates the
    # PR workflow). An earlier version required both sides to be non-None before
    # comparing, which failed OPEN: an analysis recorded against no culprit PR
    # attached to an attribution that had since found one, and described a pull
    # request it had never seen. Found by review on PR #2354.
    if ana and ana.get("culprit_pr") != top.get("pr"):
        ana = {}
    proposals = []
    for i, prop in enumerate(ana.get("proposals") or []):
        if not isinstance(prop, dict):
            continue
        pid = proposal_id(fix_pr, i)
        proposals.append(
            {
                "id": pid,
                "bucket": prop.get("bucket"),
                "title": prop.get("title"),
                "text": prop.get("text"),
                "rationale": prop.get("rationale"),
                "confidence": prop.get("confidence"),
                "decision": (dec["proposals"].get(pid) or {}).get("decision"),
                "decision_note": (dec["proposals"].get(pid) or {}).get("note"),
                "decided_at": (dec["proposals"].get(pid) or {}).get("at"),
            }
        )

    out = {
        "fix_pr": fix_pr,
        "fix_title": att.get("fix_title"),
        "fix_url": att.get("fix_url"),
        "fix_merged_at": att.get("fix_merged_at"),
        "culprit_pr": top.get("pr"),
        "culprit_subject": top.get("subject"),
        "culprit_commits": top.get("commits") or [],
        "culprit_files_touched": top.get("largest_commit_files"),
        "verdict": att.get("verdict"),
        "confidence": att.get("confidence"),
        "flags": att.get("flags") or [],
        "signal_weight": att.get("signal_weight"),
        "analysis_present": bool(ana),
        "link_verdict": ana.get("culprit_link_verdict"),
        "link_reason": ana.get("culprit_link_reason"),
        "root_cause_class": ana.get("root_cause_class"),
        "root_cause": ana.get("root_cause"),
        "why_review_missed": ana.get("why_review_missed"),
        "why_tests_missed": ana.get("why_tests_missed"),
        "prompt_injection_observed": bool(ana.get("prompt_injection_observed")),
        "proposals": proposals,
        "human_link_decision": (dec["links"].get(str(fix_pr)) or {}).get("decision"),
        "human_link_note": (dec["links"].get(str(fix_pr)) or {}).get("note"),
    }
    if include_evidence:
        out["evidence"] = att.get("evidence") or []
        out["notes"] = att.get("notes") or []
    return out


def list_reports() -> list[dict]:
    """Summaries for the list view, newest fix PR first."""
    out: list[dict] = []
    for name in os.listdir(reports_dir()):
        if not name.endswith(".json"):
            continue
        stem = name[:-5]
        if not stem.isdigit():
            continue
        rep = load_report(int(stem), include_evidence=False)
        if rep is None:
            continue
        buckets: dict[str, int] = {}
        undecided = 0
        for prop in rep["proposals"]:
            b = str(prop.get("bucket") or "?")
            buckets[b] = buckets.get(b, 0) + 1
            if not prop.get("decision"):
                undecided += 1
        out.append(
            {
                "fix_pr": rep["fix_pr"],
                "fix_title": rep["fix_title"],
                "fix_url": rep["fix_url"],
                "fix_merged_at": rep["fix_merged_at"],
                "culprit_pr": rep["culprit_pr"],
                "culprit_subject": rep["culprit_subject"],
                "verdict": rep["verdict"],
                "confidence": rep["confidence"],
                "flags": rep["flags"],
                "link_verdict": rep["link_verdict"],
                "root_cause_class": rep["root_cause_class"],
                "analysis_present": rep["analysis_present"],
                "proposal_buckets": buckets,
                "proposals_total": len(rep["proposals"]),
                "proposals_undecided": undecided,
                "human_link_decision": rep["human_link_decision"],
            }
        )
    out.sort(key=lambda r: r["fix_pr"], reverse=True)
    return out


def load_bundle(fix_pr: int) -> dict | None:
    return _read_json(os.path.join(bundles_dir(), f"bundle-{fix_pr}.json"))


# ── state ────────────────────────────────────────────────────────────────────


def load_state() -> dict:
    st = _read_json(state_path()) or {}
    st.setdefault("schema", 1)
    st.setdefault("repos", [])
    st.setdefault("last_scan", None)
    return st


def save_state(state: dict) -> None:
    with _exclusive(state_path()):
        _write_json_atomic(state_path(), state)


def touch_scan(summary: dict | None = None) -> dict:
    with _exclusive(state_path()):
        st = load_state()
        st["last_scan"] = {
            "at": time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime()),
            **(summary or {}),
        }
        _write_json_atomic(state_path(), st)
        return st["last_scan"]
